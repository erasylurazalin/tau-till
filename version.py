"""Версия кассы Tau Till.

Одно место, из которого версия попадает и в угол экрана, и в отчёт проверки,
и в проверку обновлений.  Меняется не руками, а командой pack/release.py.

Формат обычный, три числа.  Приставка «бета» живёт отдельно, в NAME_FULL, и
означает ровно то, что означает: программа уже стоит в работающем магазине, но
её ещё есть кому чинить каждый день.
"""

VERSION = "0.6.0"
STAGE = "бета"

NAME = "Tau Till"
NAME_SHORT = "TAU"


def label():
    """То, что видит человек: «Tau Till 0.6.0 бета»."""
    return f"{NAME} {VERSION}" + (f" {STAGE}" if STAGE else "")
